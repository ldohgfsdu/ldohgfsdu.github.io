const { chromium }=require('playwright');
const path=require('path');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:390,height:844},deviceScaleFactor:1});
 const errors=[];
 page.on('pageerror',e=>errors.push(String(e)));
 await page.goto('http://127.0.0.1:8765/m1racle-anki-lab/',{waitUntil:'load'});
 await page.locator('#file').setInputFiles('/tmp/m1racle-anki/kevin-fixture.apkg');
 await page.locator('#front .m1-ic-mask').first().waitFor({timeout:30000});
 assert.equal(await page.locator('#front .m1-ic-mask').count(),2,'two initial masks');
 assert.equal(await page.locator('#front .m1-ic-mask-open').count(),0,'all initially masked');
 const img=page.locator('#front .m1-ic-wrap > img');
 await img.evaluate(el=>{el.dataset.identity='same-source-image';});
 await page.locator('#front .m1-ic-mask').first().click();
 assert.equal(await page.locator('#front .m1-ic-mask-open').count(),1,'only one mask opens');
 assert.equal(await img.getAttribute('data-identity'),'same-source-image','image node retained');
 await page.screenshot({path:'/tmp/anki-v33-individual.png'});
 await page.locator('#reveal').click();
 assert.equal(await page.locator('#front .m1-ic-mask-open').count(),2,'all masks open');
 assert.equal(await img.getAttribute('data-identity'),'same-source-image','answer revealed in place');
 assert.equal(await page.locator('#front .m1-ic-wrap > img').count(),1,'no duplicate source image');
 await page.locator('#grade button[data-grade="3"]').waitFor();
 await page.screenshot({path:'/tmp/anki-v33-all.png'});
 await page.locator('#grade button[data-grade="3"]').click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('已记录评分'),null,{timeout:15000});
 const saved=await page.evaluate(()=>Object.keys(localStorage).filter(k=>k.startsWith('m1racle_anki_review_')));
 assert.equal(saved.length,1,'one graded card');
 const undo=page.locator('#undo');await undo.waitFor();assert.equal(await undo.isDisabled(),false);
 await undo.click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('上次评分已撤销'));
 const afterUndo=await page.evaluate(()=>Object.keys(localStorage).filter(k=>k.startsWith('m1racle_anki_review_')));
 assert.equal(afterUndo.length,0,'undo removes the newly created review');
 assert.ok((await page.locator('#counts').innerText()).includes('新卡 2'));
 await page.locator('#suspend').click();
 const suspended=await page.evaluate(()=>Object.keys(localStorage).filter(k=>k.startsWith('m1racle_anki_suspend_')&&localStorage.getItem(k)==='1'));
 assert.equal(suspended.length,1,'one suspended card');
 assert.ok((await page.locator('#counts').innerText()).includes('暂停 1'));
 await page.locator('#scope').selectOption('all');
 assert.equal(await page.locator('#review').isVisible(),true);
 assert.equal(errors.length,0,'no JavaScript page errors: '+errors.join('; '));
 console.log('PASS: Kevin 2-mask import, one-by-one reveal, in-place reveal all, FSRS grade, undo, suspend, deck counts, mobile viewport');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
